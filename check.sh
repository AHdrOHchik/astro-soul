#!/usr/bin/env bash
#
# Предполётная проверка окружения.
#
#   ./check.sh          — те же проверки, но только предупреждения;
#   ./check.sh --prod   — блокирует запуск, если окружение настроено как стенд.
#                         Код выхода 1 и имя переменной в сообщении.
#
# Зачем отдельный скрипт, а не проверка в `env.ts`: значения ниже валидны сами
# по себе — они опасны только на проде. `loadEnv()` не знает, где запускается
# сервис, а `--prod` знает, потому что это решение человека.
#
# Читается только окружение процесса (переменные, экспортированные в шелле или
# переданные systemd/docker-compose). Файл `.env` не парсится намеренно: у
# скрипта нет права угадывать, какой из файлов подхватит сервис.
set -uo pipefail

usage() {
  echo "использование: $0 [--prod]" >&2
}

case "${1:-}" in
  '' | --prod) ;;
  -h | --help)
    usage
    exit 0
    ;;
  *)
    usage
    exit 2
    ;;
esac

mode="${1:---dev}"
found=0

# report VAR "чем это плохо на проде"
report() {
  echo "✗ $1=$2 — $3" >&2
  found=$((found + 1))
}

# 1. Тестовый тариф за 1 ⭐: при включённом флаге любой, кто знает код
#    `test_1`, покупает подписку за одну звезду.
if [ "${PAYMENTS_TEST_PLANS:-}" = "1" ]; then
  report PAYMENTS_TEST_PLANS 1 \
    "тестовый тариф test_1 (1 ⭐ за неделю) доступен через POST /billing/invoice"
fi

# 2. Подмена Bot API: запросы (включая платёжные) уходят не в Telegram,
#    а на чужой адрес.
base="${TELEGRAM_API_BASE_URL:-}"
base="${base%/}"
if [ -n "$base" ] && [ "$base" != "https://api.telegram.org" ]; then
  report TELEGRAM_API_BASE_URL "$base" \
    "Bot API подменён: инвойсы и платежи пойдут не в Telegram"
fi

# 3. Подставной LLM: тексты разборов и прогнозов пишет заглушка.
if [ "${LLM_FAKE:-}" = "1" ]; then
  report LLM_FAKE 1 "включён подставной провайдер LLM: пользователи получат заглушки"
fi

# 4. Выключенные лимиты запросов: в тестах это норма, в проде — приглашение
#    к перебору initData и к бесплатной генерации карт.
for name in RATE_LIMIT_PER_MIN RATE_LIMIT_CHARTS_PER_MIN RATE_LIMIT_GEO_PER_MIN; do
  value="${!name:-}"
  if [ "$value" = "0" ]; then
    report "$name" 0 "лимит запросов выключен (0 разрешено только в тестах)"
  fi
done

if [ "$found" -gt 0 ]; then
  if [ "$mode" = "--prod" ]; then
    echo "check.sh: запуск в проде запрещён — убери перечисленные переменные из окружения." >&2
    exit 1
  fi
  echo "check.sh: замечания выше допустимы только на стенде (запуск с --prod их не пропустит)." >&2
fi

exit 0
