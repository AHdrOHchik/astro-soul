-- 0026: параметры счёта, которые Telegram действительно принимает.
--
-- Две вещи, обе — про платформу, а не про продукт:
--
-- 1. `plans.title` уходит в `createInvoiceLink` как название товара. У Bot API
--    это `1–32` символа. Четыре тарифа из восьми были длиннее:
--      week_149      «Разбор личности — подписка на неделю»  36
--      month_399     «Разбор личности — подписка на месяц»   35
--      year_2990     «Разбор личности — подписка на год»     33
--      test_report_1 «Тестовый полный разбор — 1 звезда»     33
--    Telegram отвечал `400`, наш клиент превращал это в `502`, и человек видел
--    «не удалось создать счёт». Витрина при этом работала: она показывает
--    `paywall_title`, а не `title`, — поэтому дефект и не был виден глазами.
--
--    Здесь названия укорачиваются до лимита и на колонку ставится CHECK:
--    длинное название больше нельзя вставить даже сидом. Текст на витрине
--    (`paywall_title`/`paywall_subtitle`) не трогаем — он не ограничен.
--
-- 2. `subscription_period` у звёздных подписок Bot API принимает только
--    2 592 000 секунд (30 дней). У тестового тарифа стояла неделя (604 800),
--    то есть тестовый тариф за 1 ⭐ вообще не выставлялся — а именно им и
--    проверяется путь оплаты. Ставим 30 дней; недельный и годовой платный
--    тариф НЕ переделываем: это решение владельца (`payments.md` §3.6).

UPDATE plans SET title = 'Разбор личности: неделя'   WHERE code = 'week_149'    AND title = 'Разбор личности — подписка на неделю';
UPDATE plans SET title = 'Разбор личности: месяц'    WHERE code = 'month_399'   AND title = 'Разбор личности — подписка на месяц';
UPDATE plans SET title = 'Разбор личности: год'      WHERE code = 'year_2990'   AND title = 'Разбор личности — подписка на год';
UPDATE plans SET title = 'Тестовый разбор — 1 ⭐'    WHERE code = 'test_report_1' AND title = 'Тестовый полный разбор — 1 звезда';

UPDATE plans
   SET period_seconds = 2592000,
       description = '30 дней доступа за 1 ⭐. Только для проверки оплаты владельцем',
       paywall_subtitle = '1 ⭐ за 30 дней доступа, права как у месячной. Только для проверки оплаты.',
       title = 'Тестовая подписка — 1 ⭐',
       updated_at = now()
 WHERE code = 'test_1';

COMMENT ON COLUMN plans.title IS
  'Название товара в окне оплаты Telegram (createInvoiceLink.title): 1–32 символа. Для витрины — paywall_title.';

-- Гарантия на уровне схемы: длинный заголовок не должен доходить до Telegram.
ALTER TABLE plans
  ADD CONSTRAINT plans_title_fits_telegram CHECK (char_length(title) BETWEEN 1 AND 32);
