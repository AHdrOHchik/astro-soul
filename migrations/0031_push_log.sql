-- 0031_push_log.sql
-- Итерация 36, задача 4: подготовка пуша 08:00 (сам пуш — итерация 37).
--
-- Зачем таблица, если пуш уже есть. Сегодня `forecasts.push_sent_at` — одна
-- отметка на прогноз и никакого журнала: после отправки невозможно ответить ни
-- «сколько пушей ушло этому человеку за неделю», ни «почему не ушло» (отметка
-- `push_sent_at` осталась пустой, и всё). Для ежедневного пуша по расписанию
-- нужны ровно две вещи, которых в схеме нет:
--
--   1) `push_log` — что и когда отправили, с ошибкой отправки. Ключ
--      `(user_id, local_date, kind)` — это идемпотентность: повторный прогон
--      крона (или второй экземпляр, если лок не сработал) не отправит второй
--      пуш за те же местные сутки. Сутки именно **местные**: у человека в
--      UTC+7 «08:00 сегодня» — это другие сутки UTC, и хранить `date` без
--      привязки к поясу значило бы путать два разных «сегодня».
--   2) `users.push_enabled` — согласие на пуш отдельно от прогноза. Человек,
--      которому не нужен ежедневный пуш, не должен отключать сам прогноз:
--      прогноз генерируется всё равно и остаётся в приложении.
--
-- `kind` — текст, а не enum: в итерации 37 видов пуша будет больше одного
-- (прогноз дня, напоминание о разборе), и добавлять тип ради этого новую
-- миграцию с `ALTER TYPE` незачем. Значение по умолчанию `daily_forecast` —
-- единственное, что пишется сейчас.
--
-- Приватность: в журнале нет ни текста пуша, ни `telegram_id` — только
-- `user_id` (псевдоним), дата и ошибка отправки. `DELETE /me` удаляет строки
-- каскадом вместе с `users`: журнал — не бухгалтерия, восстанавливать его
-- после удаления аккаунта нечего.
--
-- Идемпотентность файла: `IF NOT EXISTS` — миграция может быть применена
-- повторно на стенде, где её уже накатывали вручную.

ALTER TABLE users
  ADD COLUMN IF NOT EXISTS push_enabled boolean NOT NULL DEFAULT true;

COMMENT ON COLUMN users.push_enabled IS
  'Согласие на ежедневный пуш 08:00 (итерация 37). Не влияет на генерацию прогноза: отказ только про доставку';

CREATE TABLE IF NOT EXISTS push_log (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Каскад: журнал не переживает удаление аккаунта (см. DELETE /me).
  user_id    uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  -- Местные сутки получателя (по `charts.data.chart.birth.place.tz`), не UTC.
  local_date date NOT NULL,
  kind       text NOT NULL DEFAULT 'daily_forecast',
  sent_at    timestamptz NOT NULL DEFAULT now(),
  -- Текст ошибки Bot API. NULL — отправка прошла. Текст пуша сюда не пишется.
  error      text,
  -- Один пуш каждого вида за местные сутки. Второй INSERT на тех же сутках
  -- должен падать, а не отправлять дубль: это дешевле, чем проверка в коде.
  CONSTRAINT push_log_user_date_kind_key UNIQUE (user_id, local_date, kind)
);

COMMENT ON TABLE push_log IS
  'Журнал отправленных пушей (итерация 37). Ключ (user_id, local_date, kind) — идемпотентность суточного пуша';
COMMENT ON COLUMN push_log.local_date IS
  'Местные сутки получателя, а не UTC: 08:00 в UTC+7 — другие сутки';
COMMENT ON COLUMN push_log.error IS
  'Текст ошибки Bot API, NULL при успехе; текст пуша не сохраняется';

-- Ночной джоб ищет «кому ещё не отправили сегодня» — индекс ровно под это.
CREATE INDEX IF NOT EXISTS push_log_sent_at_idx ON push_log (sent_at);
