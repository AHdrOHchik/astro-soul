-- Что нормализация поправила в каждой главе (итерация 18, задача 2).
--
-- Правило новое: провал «формы» (абзацы, длина, повторы) больше не убивает
-- главу — текст нормализуется детерминированно и показывается с пометкой.
-- Чтобы это можно было проверить постфактум, кроме `validation` (там только
-- провалы) нужен второй столбец: что именно склеили/разрезали/обрезали.
--
-- Формат: `{"core": {"normalized": ["paragraphs_split"], "warnings": ["repeats"]}, ...}`.
-- Отдельной таблицей не делаем: запись читается только вместе с разбором,
-- а `chapters`/`validation` уже живут здесь же.
ALTER TABLE reports ADD COLUMN IF NOT EXISTS normalization jsonb;

COMMENT ON COLUMN reports.normalization IS
  'Правки нормализатора по главам: {section: {normalized: [код], warnings: [код]}} (normalize.ts, итерация 18)';
