-- QA-11: платежи, по которым доступ не выдан.
--
-- Отдельное значение enum'а, а не 'failed': `failed` — про техническую ошибку
-- обработки, `rejected` — про отказ по деньгам (нет серверного инвойса, сумма
-- не совпала с ценой плана, неизвестный план). Статус виден поддержке и
-- считается в `payments_rejected_30d` / `amount_mismatch_30d`.
--
-- `ALTER TYPE ... ADD VALUE` вынесен в отдельный файл: новое значение нельзя
-- использовать в той же транзакции, в которой оно добавлено, а мигратор
-- выполняет каждый файл в BEGIN/COMMIT.
ALTER TYPE payment_status ADD VALUE IF NOT EXISTS 'rejected';
