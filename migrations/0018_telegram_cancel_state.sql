-- Отмена автопродления в Telegram — отдельное состояние, потому что вызов Bot
-- API живёт вне транзакции удаления и может не пройти.
--
-- Значение enum добавляется своим файлом: `ALTER TYPE ... ADD VALUE` нельзя
-- использовать в той же транзакции, где оно появляется (правило из 0013/0016).
--
--   none      — вызова не было: подписки нет либо отмена не требовалась;
--   cancelled — Telegram подтвердил `editUserStarSubscription(is_canceled: true)`;
--   failed    — вызов не прошёл, но попытки не исчерпаны: ночной джоб повторит;
--   gave_up   — 5 неудач или истекло окно возврата: больше не пробуем.
CREATE TYPE telegram_cancel_state AS ENUM ('none', 'cancelled', 'failed', 'gave_up');
