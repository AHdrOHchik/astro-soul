-- Блокер A (итерация 11): `entitlements.status` получает значение `revoked`.
--
-- `active` → «право есть», `refunded` → «звёзды вернули», `revoked` → «право
-- снято волей пользователя» (`DELETE /me`). Отдельное значение нужно, чтобы
-- удаление не выглядело как возврат денег: по `refunded` бухгалтерия ищет
-- возвращённые платежи, и подмешивать туда удалённые аккаунты нельзя.
--
-- Значение добавляется своим файлом: `ALTER TYPE ... ADD VALUE` нельзя
-- использовать в той же транзакции, где оно добавлено, а мигратор выполняет
-- каждый файл в BEGIN/COMMIT (то же ограничение, что у 0013).
ALTER TYPE entitlement_status ADD VALUE IF NOT EXISTS 'revoked';
