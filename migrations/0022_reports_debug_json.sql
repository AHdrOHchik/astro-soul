-- Сырой ответ модели на провал валидации (живой прогон 2026-11-16).
--
-- Валидатор говорит «1 абзац вне 3–6», но не говорит, что именно написала
-- модель. Без сырого ответа чинить промпт приходится догадками: `validation`
-- хранит только правила, а `chapters` главу-неудачницу не сохраняет вовсе —
-- провал прерывает конвейер.
--
-- Формат: JSON-массив по попыткам
--   [{"key": "talents", "attempt": 1, "raw": "первые 2000 знаков", "cats": ["paragraphs"]}]
-- Обрезается в коде (2000 знаков): полный текст главы в диагностике не нужен,
-- а место в строке — нужно. ПДн здесь нет: в промпт и ответ попадают только
-- `chart_facts`.
--
-- NULL — провал не по валидации (провайдер, лимит) или строки до миграции.
ALTER TABLE reports
  ADD COLUMN debug_json jsonb;

COMMENT ON COLUMN reports.debug_json IS
  'Сырые ответы модели на провалы валидации: [{key, attempt, raw (2000 знаков), cats}]';
