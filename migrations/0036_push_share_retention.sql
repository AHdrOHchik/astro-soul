-- 0036_push_share_retention.sql
-- Итерация 39, долги 8.5 из итерации 38 (контракт 1.6.14).
--
-- Три вещи, которые не были сделаны в 1.6.13 и без которых эксплуатация
-- накапливает мусор и слепые зоны:
--
--   1) `push_log.sent` — «сообщение действительно ушло». До этой миграции
--      строка журнала появлялась **до** отправки (заявка, чтобы не отправить
--      дважды), а `error IS NULL` означала и «ушло», и «процесс умер между
--      заявкой и отправкой». Первое — норма, второе — тихая потеря пуша:
--      человек согласие дал, карта есть, сообщения нет, и никто об этом не
--      узнает. Колонка разделяет эти два состояния, а метрика
--      `push_claimed_not_sent_24h` их считает.
--
--      `DEFAULT true` — именно для старых строк: они писались до появления
--      колонки, `error IS NULL` у них означал «отправлено» (иначе строка
--      получила бы текст ошибки). Новые строки пишут `sent = false` явно и
--      поднимают флаг в `finishPush`.
--
--   2) `push_runs` за 30 дней — агрегаты циклов нужны для `/health` и метрик
--      за сутки; хранить их вечно незачем, а таблица растёт на 1440 строк в
--      сутки (планировщик тикает каждую минуту).
--
--   3) `share_cards.last_opened_at` — какие карточки кто-то открывал по ссылке
--      `sh_`. Чистка «старше 30 дней» без этого поля ломала бы работающие
--      ссылки в чужих переписках: карточка без открытий — кандидат на
--      удаление, открытая — нет.
--
-- Идемпотентность: `IF NOT EXISTS`/`ADD COLUMN IF NOT EXISTS` — файл можно
-- накатить повторно на стенде.

ALTER TABLE push_log
  ADD COLUMN IF NOT EXISTS sent boolean NOT NULL DEFAULT true;

COMMENT ON COLUMN push_log.sent IS
  'Сообщение действительно доставлено в Bot API (1.6.14). false и error IS NULL — процесс умер между заявкой и отправкой';

-- Метрика `push_claimed_not_sent_24h` смотрит ровно на «заявка была, отправки
-- нет» за сутки: частичный индекс дешевле любого скана по журналу.
CREATE INDEX IF NOT EXISTS push_log_unsent_idx
  ON push_log (sent_at)
  WHERE sent = false AND error IS NULL;

ALTER TABLE share_cards
  ADD COLUMN IF NOT EXISTS last_opened_at timestamptz;

COMMENT ON COLUMN share_cards.last_opened_at IS
  'Когда карточку последний раз открывали по ссылке sh_ (1.6.14). Карточки с открытиями не удаляются чисткой';

CREATE INDEX IF NOT EXISTS share_cards_last_opened_idx
  ON share_cards (last_opened_at)
  WHERE last_opened_at IS NOT NULL;
