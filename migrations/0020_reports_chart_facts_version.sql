-- Версия блока `chart_facts` в промпте (задача C итерации 12).
--
-- С 1.2 в промпт уходят отобранные факторы (7–9 позиций), а не полная карта.
-- Без этой колонки нельзя ответить на вопрос «разбор дешёвый потому что
-- короче или потому что отбор сломался»: `llm_tokens_in` падает в обоих
-- случаях, а причина разная.
--
-- Значение по умолчанию — `v1.1`: строки, созданные до этой миграции, писались
-- полной картой, и переписывать историю нельзя.
ALTER TABLE reports
  ADD COLUMN chart_facts_version text NOT NULL DEFAULT 'v1.1';

COMMENT ON COLUMN reports.chart_facts_version IS
  'Версия блока chart_facts в промпте: v1.1 — полная карта, v1.2 — top factors';
