interface RefusalRule {
  readonly reason: RefusalReason;
  readonly pattern: RegExp;
  /** «Спроси у карты»-контексты, где слова не значат тему (например, «не про здоровье»). */
  readonly exempt?: RegExp;
}

/**
 * Регулярки широкие осознанно: пропустить медицинский вопрос в модель дороже,
 * чем один раз отказать на граничном. Каждая причина — свой набор слов, потому
 * что отказ одинаковый по форме, но разный по тексту.
 */
const RULES: readonly RefusalRule[] = [
  {
    reason: 'medical',
    pattern:
      /диагноз|заболев|болезн|болит|симптом|лечени|лечить|лек[ао]рств|таблетк|дозировк|анализ[ыа]|терапи|врач|онколог|беременн|заберемен/iu,
    // «Энергия», «режим», «сон» — это про состояние, а не про здоровье: такие
    // вопросы карта разбирать может.
    exempt: /энерги|режим|\bсон\b|устал/iu,
  },
  {
    reason: 'legal',
    // `\b` в JavaScript опирается на ASCII-`\\w`, поэтому для кириллицы граница
    // задаётся явным просмотром по буквам: иначе «иск» не находится вовсе.
    pattern:
      /юрист|адвокат|нотариус|наследств|налог|вычет|договор|штраф|уголовн|суд(?:[аеуы]|ом|ах)?(?![а-яё])|(?<![а-яё])иск(?![а-яё])/iu,
  },
  {
    reason: 'money',
    pattern:
      /кредит|ипотек|займ|вклад|инвест|акци|биржа|крипт|облигаци|заработ|разбогате|выигра|лотере/iu,
  },
  {
    reason: 'death',
    pattern:
      /смерт|умр[её]т|умр[её]шь|умира|похорон|кончин|(?<![а-яё])рак(?![а-яё])|онкологи|инсульт|инфаркт/iu,
  },
  {
    reason: 'third_party',
    // Порядок слов в живом вопросе любой, поэтому две формы: «он … любит» и
    // «любит … муж». Одна регулярка не покрывала «Меня любит мой муж?».
    pattern:
      /(он|она|муж|жена|партн[её]р|бывш|начальник|подруг|друг|мама|папа|мать|отец|сын|дочь|реб[её]нок|коллег)\w*[^.!?]{0,40}(любит|думает|изменя|верн[её]тся|хочет|чувству|планир|скуча|жд[её]т)/iu,
  },
  {
    reason: 'third_party',
    pattern:
      /(любит|думает|изменя|верн[её]тся|чувству|скуча|планир)[^.!?]{0,40}(он|она|муж|жена|партн[её]р|бывш|начальник|подруг|друг|мама|папа|мать|отец|сын|дочь|реб[её]нок|коллег)/iu,
  },
  {
    reason: 'adult',
    pattern: /секс|интим|18\+|эротич|порн/iu,
  },
];

/**
 * Проверка на отказ. Порядок правил фиксирован: при двух совпадениях причина
 * должна быть одна и та же всегда, иначе одинаковые вопросы получат разные
 * тексты ответа и разную статистику.
 */
export function refusalOf(question: string): RefusalReason | null {
  for (const rule of RULES) {
    if (!rule.pattern.test(question)) {
      continue;
    }
    if (rule.exempt !== undefined && rule.exempt.test(question)) {
      continue;
    }
    return rule.reason;
  }

  return null;
}

const TOPIC_RULES: readonly { topic: QuestionTopic; pattern: RegExp }[] = [
  { topic: 'love', pattern: /любов|отношен|чувств|свидан|партн|брак|расставан|симпат/i },
  { topic: 'career', pattern: /работ|карьер|проект|начальник|коллег|бизнес|уч[её]б|собес/i },
  { topic: 'money', pattern: /деньг|доход|зарплат|финанс|трат|бюджет/i },
  { topic: 'health', pattern: /здоров|энерги|сон|устал|спорт|тело|режим/i },
  { topic: 'self', pattern: /себя|самооцен|страх|тревог|смысл|цель|привычк/i },
];

/**
 * Тема вопроса — для аналитики вместо текста.
 *
 * Классификация грубая и детерминированная: она нужна, чтобы видеть «о чём
 * спрашивают», и не претендует на точность. Вопрос может подойти под две темы
 * — берём первую по фиксированному порядку.
 */
export function topicOf(question: string): QuestionTopic {
  for (const rule of TOPIC_RULES) {
    if (rule.pattern.test(question)) {
      return rule.topic;
    }
  }

  return 'other';
}
