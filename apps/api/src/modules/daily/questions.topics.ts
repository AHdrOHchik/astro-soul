/**
 * Отказ до модели и тема вопроса.
 *
 * Два разных механизма, которые легко перепутать:
 *
 *   • **Отказ** (`refused`) — детерминированная проверка регулярками, до
 *     вызова модели. Квота не тратится, денег нет, ответ — фиксированный текст.
 *     Причины — закрытый список: фронт показывает разные тексты (и разные
 *     подсказки «о чём можно»), поэтому «просто отказ» недостаточно.
 *   • **Тема** (`topic`) — грубая классификация для аналитики. Она попадает в
 *     `events.props` вместо текста вопроса: тема нужна продукту, текст — нет.
 */

export const REFUSAL_REASONS = [
  'medical',
  'legal',
  'money',
  'death',
  'third_party',
  'adult',
] as const;

export type RefusalReason = (typeof REFUSAL_REASONS)[number];

export const TOPICS = ['love', 'career', 'money', 'self', 'health', 'other'] as const;

export type QuestionTopic = (typeof TOPICS)[number];

