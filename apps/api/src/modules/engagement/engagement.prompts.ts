/**
 * Промпты удержания. Правила те же, что у разбора: «ты», никаких диагнозов,
 * смерти, гарантий денег и юридических советов, никаких дат и обещаний.
 *
 * В промпт попадает только `chart_facts` (тот же сериализатор, что у разбора)
 * и — у вопроса — текст вопроса. Дата рождения, место и имя не уходят.
 */

export const ENGAGEMENT_SYSTEM_PROMPT = [
  'Ты — редактор астрологического мини-приложения. Пишешь коротко, на «ты», без лести и запугивания.',
  'Запрещено: диагнозы и здоровье как тема, смерть, беременность, гарантии дохода, инвестиции, налоги и юридические советы,',
  '«карма», «судьба», «предназначение», любые даты, сроки и обещания результата.',
  'Опирайся только на факты карты из сообщения. Не придумывай планет, домов и аспектов, которых там нет.',
  'Отвечай строго JSON без пояснений и без markdown.',
].join(' ');

export interface ForecastPromptInput {
  readonly facts: string;
  readonly date: string;
  readonly paid: boolean;
}

/** Прогноз: полный (3–6 предложений + фокус) или урезанный (1–2). */
export function forecastPrompt(input: ForecastPromptInput): string {
  const shape = input.paid
    ? '{"text": "3–6 предложений", "focus": "career|love|money|health|self"}'
    : '{"text": "1–2 предложения"}';

  return [
    `Карта:\n${input.facts}`,
    '',
    `Местная дата: ${input.date}.`,
    input.paid
      ? 'Напиши прогноз на этот день: что сегодня заметно в ритме, решениях и контактах. 3–6 предложений, без списков и заголовков.'
      : 'Напиши короткий прогноз на этот день: 1–2 предложения, только самое заметное.',
    input.paid
      ? 'focus — одно слово из списка: career, love, money, health, self. health — только энергия и режим, никаких диагнозов.'
      : 'Без поля focus.',
    `Формат: ${shape}`,
  ].join('\n');
}

export interface AskPromptInput {
  readonly facts: string;
  readonly question: string;
}

/**
 * «Спроси карту». Вопрос уходит в модель как есть, но в БД и логи — нет:
 * там только длина и тема.
 */
export function askPrompt(input: AskPromptInput): string {
  return [
    `Карта:\n${input.facts}`,
    '',
    `Вопрос: ${input.question}`,
    '',
    'Ответь по фактам карты: 2–5 предложений, до 1200 знаков. Если вопрос не про карту — скажи это одной фразой.',
    'based_on — 1–5 позиций карты, на которые ты реально опирался, в том виде, как они даны в фактах (например «Луна в Льве»).',
    'Если опереться не на что — пустой массив. Не выдумывай позиции.',
    'Формат: {"answer": "текст", "based_on": ["позиция"]}',
  ].join('\n');
}
