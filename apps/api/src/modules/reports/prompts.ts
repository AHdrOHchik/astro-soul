/** Отдельные требования при `unknown` для `core` (в конце) и `summary` (в начале). */
export const UNKNOWN_CORE_NOTE =
  'Последней фразой честно скажи, что домов в разборе нет и почему: время рождения неизвестно.';
export const UNKNOWN_SUMMARY_NOTE =
  'Первой фразой главы скажи, что домов в разборе нет, потому что время рождения неизвестно, и что выводы о работе и отношениях поэтому осторожнее. При approximate: «дома могут быть сдвинуты».';

export interface ChapterPromptInput {
  readonly key: Exclude<SectionKey, 'summary'>;
  readonly chartFacts: string;
  readonly thesis: string;
  readonly focusBlock: string;
  readonly previousSummary: string;
  readonly timePrecision: TimePrecision;
  readonly examples: readonly string[];
}

function rangeOf(key: SectionKey): string {
  const section = SECTIONS.find((candidate) => candidate.key === key);
  if (section === undefined) {
    return '';
  }
  return `${section.min.toLocaleString('ru-RU')}–${section.max.toLocaleString('ru-RU')} знаков`;
}

export function chapterPrompt(input: ChapterPromptInput): string {
  const rules = SECTION_RULES[input.key];
  const note = TIME_PRECISION_NOTE[input.timePrecision];
  const unknownTail =
    input.timePrecision === 'unknown' && input.key === 'core' ? `\n${UNKNOWN_CORE_NOTE}` : '';
  const examples =
    input.examples.length === 0
      ? ''
      : `\nПримеры того, как надо (не копируй факты, копируй способ):\n${input.examples.join('\n\n')}\n`;

  return `Глава: ${input.key}. Объём: ${rangeOf(input.key)}.

Правила этой главы:
${rules}

Факты карты:
${input.chartFacts}

Главный тезис разбора: ${input.thesis}
Фокусы этого разбора:
${input.focusBlock}

Уже написано (краткая сводка, не повторяй формулировки и не пересказывай):
${input.previousSummary}

${note}
${unknownTail}${examples}
Напиши главу. Требования:
1. Опирайся на факторы из правил этой главы — не на все подряд. Каждый названный фактор должен дать следствие для человека в этой же фразе или следующей.
2. Своя мысль, а не сводка предыдущих глав: смотри на общие факторы под своим углом.
3. Один конфликт факторов — максимум, и он назван словами в двух-трёх предложениях: слой, слой, как они встречаются в жизни. Одним предложением конфликт не описывать.
4. Не начинай с общих слов о личности. Первое предложение — наблюдение, которое можно проверить на себе.
5. Не упоминай, что это разбор, карта, отчёт, глава. Не обращайся к читателю «вы».`;
}

export function summaryPrompt(input: {
  readonly thesis: string;
  readonly digests: readonly string[];
  readonly timePrecision: TimePrecision;
}): string {
  return `Ниже тезис разбора и краткие сводки глав. Напиши заключительную главу «Итог: что с этим делать». Объём 500–750 знаков.

Тезис: ${input.thesis}

Сводки глав:
${input.digests.map((digest, index) => `${index + 1}. ${digest}`).join('\n')}

Требования:
1. Ровно три действия. Каждое начинается с глагола, выполнимо за неделю без покупок, разрешений и отпуска, и проверяемо: понятно, сделал или нет.
2. Каждое действие вытекает из конкретного факта, названного в главах. Новых факторов и новых трактовок не вводить.
3. Действия должны быть неудобными, но посильными: не «прислушайся к себе», а «назови цену вслух один раз — человеку, который может её обсудить».
4. Никаких обещаний результата и сроков («через месяц почувствуешь»).
5. Последняя фраза — дословно: «Разбор — инструмент саморефлексии, а не предсказание и не замена специалисту.»
6. Не пересказывай главы: «как уже говорилось» запрещено.

${input.timePrecision === 'unknown' ? UNKNOWN_SUMMARY_NOTE : TIME_PRECISION_NOTE[input.timePrecision]}`;
}

