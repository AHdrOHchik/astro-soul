/** Правила разделов (`{{section_rules}}`), по одной записи на раздел. */
export const COMPAT_SECTION_RULES: Readonly<Record<'clicks' | 'friction' | 'scenario' | 'steps', string>> = {
  clicks: `Отвечай на вопрос: что у вас совпадает так, что это узнаётся с первой фразы.
Используй обязательно: пары светил (Солнце–Луна, Луна–Луна, Солнце–Солнце), самый сильный гармоничный кросс-аспект, разницу по доминирующей стихии.
Обязательно: два-три конкретных совпадения в поведении («оба…», «вам обоим…») и одно неожиданное объяснение, почему это работает.
Запрещено: лесть («идеальная пара»), проценты, обещания, советы.
Этот раздел продаёт: человек должен узнать себя и партнёра, а не прочитать про аспекты.`,
  friction: `Отвечай на вопрос: где именно вас заедает друг о друга.
Используй обязательно: самый сильный напряжённый кросс-аспект (квадрат или оппозиция), Сатурн или Марс в паре, разницу по кресту.
Обязательно: конкретный триггер (что делает один и как это читает второй) и механизм, по которому мелкое расхождение вырастает в ссору.
Запрещено: обвинения в адрес партнёра, «токсичный», «абьюз», советы уходить, предсказания расставания, диагнозы.
Не смягчай до «бывает по-разному»: раздел покупают за узнавание, а не за утешение.`,
  scenario: `Отвечай на вопрос: как вы разговариваете, когда не согласны, и что в этом разговоре ломается первым.
Используй обязательно: Меркурий (аспекты и знак), Марс как способ злиться, один аспект внешней планеты, если он есть.
Обязательно: узнаваемый сценарий ссоры по шагам (кто замечает первым, что происходит дальше, чем это заканчивается) и одна точка, где разговор можно развернуть.
Запрещено: советы «просто поговорите», описания чувств вместо механики, утверждения о том, кто прав.
Пиши о механике, а не о морали.`,
  steps: `Этот раздел — три конкретных действия на неделю, а не рассуждение.
Форма: ровно три пункта списком, каждый начинается с маркера «—» и с глагола: что сделать, когда и в какой ситуации. Один пункт — 2–3 предложения.
Опирайся на самую сильную сторону пары из фактов: то, что у вас уже получается, легче превратить в действие.
Запрещено: «будьте терпимее», «слушайте друг друга», любые советы без ситуации; медицинские, финансовые и юридические рекомендации; обещания результата.
После пунктов — дословно эта подпись отдельным абзацем:
${COMPAT_DISCLAIMER_TEXT}`,
};

export function compatSectionPrompt(input: {
  readonly key: 'clicks' | 'friction' | 'scenario' | 'steps';
  readonly facts: string;
  readonly focusBlock: string;
  readonly previousSummary: string;
}): string {
  const rules = COMPAT_SECTION_RULES[input.key];
  const forma =
    input.key === 'steps'
      ? `Форма: ровно три пункта списком маркером «—», в каждом 2–3 предложения, и последним абзацем — подпись:\n${COMPAT_DISCLAIMER_TEXT}`
      : COMPAT_FORMA_BLOCK;

  return `Ниже факты пары, посчитанные движком, и 2–3 факта, на которых держится именно этот раздел.

Факты пары:
${input.facts}

Факты этого раздела:
${input.focusBlock}

Что уже сказано в предыдущих разделах (не повторяй):
${input.previousSummary}

Правила раздела:
${rules}

${forma}

Верни только текст раздела.`;
}
