import { COMPAT_DISCLAIMER } from './compat-validators';

/**
 * Промпты совместимости (`prompts_v1.5`).
 *
 * Почему отдельная версия, а не общий `PROMPT_VERSION`: разбор остаётся на
 * `prompts_v1.4`, и его тексты не менялись. Если бы версия была общей, уже
 * проданные разборы получили бы в `reports.prompt_version` чужую строку, и
 * первая же жалоба «текст стал другим» разбиралась бы по неверной версии.
 *
 * Продукт другой: не разбор одного человека, а текст про пару. Отсюда три
 * правила, которых нет в разборе:
 *   • партнёр — «партнёр», без рода: пола мы не знаем;
 *   • никаких вердиктов и процентов: «вам не подходите» — утверждение о двух
 *     живых людях, которое мы не имеем права делать;
 *   • первые 200 знаков — без астрологических терминов: человек покупает про
 *     себя, а не про аспекты.
 */
export const COMPAT_PROMPT_VERSION = 'prompts_v1.5';

/** Служебная подпись последнего раздела. Источник — `compat-validators.ts`, чтобы в промпте и в проверке была одна строка. */
export const COMPAT_DISCLAIMER_TEXT = COMPAT_DISCLAIMER;

